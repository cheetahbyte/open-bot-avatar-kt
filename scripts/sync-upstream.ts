// Regenerates what comes from the TypeScript engine: the catalog and the parity fixtures.
// Usage: node scripts/sync-upstream.ts <path to an open-bot-avatar checkout>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const upstream = resolve(process.argv[2] ?? '');
const root = resolve(import.meta.dirname, '..');
const src = join(upstream, 'packages/core/src');
const { examples, renderAvatarSvg, validateAvatar, computePose, createAnimator, pointerGaze } = await import(join(src, 'index.ts'));
const { liveFrame } = await import(join(src, 'render.ts'));
const { hashString } = await import(join(src, 'motion.ts'));

const kotlinString = (s: string) => JSON.stringify(s).replaceAll('$', '\\$');
const decimal = (n: number) => (Number.isInteger(n) ? n.toFixed(1) : String(n));
const entry = (d: any) => `    AvatarDefinition(
        id = ${kotlinString(d.id)},
        name = ${kotlinString(d.name)},
        path = ${kotlinString(d.body.path)},
        eyes = AvatarEyes(x = ${decimal(d.eyes.x)}, y = ${decimal(d.eyes.y)}, spacing = ${decimal(d.eyes.spacing)}, scale = ${decimal(d.eyes.scale)}),
    ),`;

const galleryDir = join(upstream, 'gallery');
const taken = new Set(examples.map((e: any) => e.id));
const gallery = readdirSync(galleryDir)
  .filter((f) => f.endsWith('.json') && f !== 'colors.json')
  .map((f) => {
    const result = validateAvatar(JSON.parse(readFileSync(join(galleryDir, f), 'utf8')));
    if (!result.ok) throw new Error(`${f}: ${result.errors.join('; ')}`);
    return result.value;
  })
  .filter((d: any) => !taken.has(d.id))
  .sort((a: any, b: any) => a.name.localeCompare(b.name));
const colors = JSON.parse(readFileSync(join(galleryDir, 'colors.json'), 'utf8'));

writeFileSync(join(root, 'core/src/main/kotlin/re/leob/openbotavatar/kt/AvatarCatalogData.kt'), `package re.leob.openbotavatar.kt

// Generated by scripts/sync-upstream.ts. Do not edit.

internal val generatedExamples: List<AvatarDefinition> = listOf(
${examples.map(entry).join('\n')}
)

internal val generatedGallery: List<AvatarDefinition> = listOf(
${gallery.map(entry).join('\n')}
)

internal val generatedColors: Map<String, String> = mapOf(
${Object.entries(colors).map(([id, hex]) => `    ${kotlinString(id)} to ${kotlinString(hex as string)},`).join('\n')}
)
`);

const defs = [...examples, ...gallery] as any[];

const everyone = [{ time: 1.2 }, { time: 7.31, motion: 'happy' }, { time: 3.3, motion: 'thinking', color: '#1FB', eyeColor: '#ffffff' }];
const thorough = [
  { depth: 0 },
  { depth: 14, time: 2 },
  { depth: 2.3, time: 2 },
  { view: { yaw: 1.3, pitch: -0.2 }, time: 4 },
  { view: { yaw: 3.0, pitch: 0.4 } },
  { gaze: { x: 0.8, y: -0.6, weight: 0.5 }, time: 0.4 },
  { gaze: { x: -1, y: 1 }, reducedMotion: true },
  { reducedMotion: true, motion: 'happy', size: 256 },
  { time: 5, motion: 'happy', motionBlend: { from: { motion: 'thinking', blend: { from: 'idle', t: 0.4 } }, t: 0.55 } },
];
const svgs: unknown[] = [];
const frames: unknown[] = [];
defs.forEach((definition, i) => {
  for (const options of [...everyone, ...(i % 4 === 0 ? thorough : [])]) svgs.push({ id: definition.id, options, svg: renderAvatarSvg(definition, options) });
  for (const size of [28, 64, 180]) {
    const frame = liveFrame(definition, { time: 2.5, size });
    frames.push({ id: definition.id, size, keys: frame.shapes.map((s: any) => s.key), paths: frame.paths.map((p: any) => p.id) });
  }
});

const box = examples[0];
const invalid: unknown[] = [
  null, [], 'text', {}, { ...box, extra: 1 }, { ...box, version: 2 }, { ...box, id: 'Bad Id' }, { ...box, name: '<b>' }, { ...box, name: '' },
  { ...box, body: 'x' }, { ...box, body: { path: 7 } }, { ...box, body: { path: '', more: 1 } }, { ...box, body: { path: 'M0 0 L10 10 X' } },
  { ...box, body: { path: 'L1 2' } }, { ...box, body: { path: 'Z' } }, { ...box, body: { path: 'M1 1 C1 2' } }, { ...box, body: { path: 'M500 500L1 1Z' } },
  { ...box, body: { path: 'M20 20A5 5 0 2 1 30 30Z' } }, { ...box, body: { path: 'M20 20H80V80H20Z' } }, { ...box, body: { path: 'M1 1H99V99H1Z' } },
  { ...box, body: { path: 'M40 40H50V50H40Z' } }, { ...box, eyes: 1 }, { ...box, eyes: { x: 50, y: 40 } }, { ...box, eyes: { ...box.eyes, w: 1 } },
  { ...box, eyes: { ...box.eyes, scale: 2 } }, { ...box, eyes: { ...box.eyes, spacing: 2 } }, { ...box, eyes: { ...box.eyes, x: 2 } },
].map((input) => ({ input, result: validateAvatar(input) }));

const poses: unknown[] = [];
for (const seed of ['mug', 'ghost', 'x'].map(hashString)) {
  for (const motion of ['idle', 'thinking', 'happy']) {
    for (let time = 0; time < 40; time += 1.37) {
      for (const extra of [{}, { reducedMotion: true }, { gaze: { x: 0.4, y: -0.9, weight: 0.7 } }, { blend: { from: { motion: 'happy' }, t: 0.3 } }]) {
        const input = { seed: seed | 0, time, motion, reducedMotion: false, ...extra };
        poses.push({ input, pose: computePose({ ...input, seed }) });
      }
    }
  }
}

const animator = createAnimator();
const script: unknown[] = [];
for (let k = 0; k < 120; k++) {
  const now = 1000 + k * 16;
  const motion = k < 20 ? 'idle' : k < 30 ? 'happy' : k < 80 ? 'thinking' : 'idle';
  const target = k > 10 && k < 60 ? { x: Math.sin(k / 9), y: Math.cos(k / 7) / 2 } : null;
  const hold = k > 90 && k < 100;
  script.push({ input: { now, motion, target, hold }, step: animator.step({ now, motion, target, hold, reducedMotion: false }) });
}

const gazes = [[0, 0], [300, 90], [-40, 500], [50, 50]].map(([x, y]) => ({ x, y, gaze: pointerGaze({ x, y }, { left: 10, top: 20, width: 96, height: 96 }, { x: 0.5, y: 0.42 }) }));

const hashes = ['', 'a', 'mug', 'controller'].map((s) => ({ s, hash: hashString(s) | 0 }));
const json = JSON.stringify({ defs, svgs, frames, invalid, poses, animator: script, gazes, hashes });
writeFileSync(join(root, 'core/src/test/resources/parity.json.gz'), gzipSync(json, { level: 9 }));
console.log(`${defs.length} definitions, ${svgs.length} svgs, ${(json.length / 1e6).toFixed(1)} MB raw`);
